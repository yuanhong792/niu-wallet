/* 个人多链：一个币一张卡。每张卡独立收发，不再共用一个网络下拉框和发送表单。 */
(() => {
  'use strict';
  const $=id=>document.getElementById(id),token=document.querySelector('meta[name="niu-token"]').content;
  const LOCKED='解锁后显示';
  let state=null,working=false;
  const balances=new Map();   // networkId -> {ASSET: '0.0'}
  const pendingBal=new Map(); // networkId -> 未确认净额
  const netError=new Map();   // networkId -> 整条网络查询失败的原因
  const assetError=new Map(); // "net:asset" -> 单个币查询失败的原因
  const draftIds=new Map();   // "net:asset" -> 后端 draftId

  const message=text=>{$('personalMessage').textContent=text;};

  // Every call gets a hard timeout. Without one a stalled request leaves the page stuck on
  // 「正在处理…」 forever, with every button dead because work() never releases its guard.
  async function api(action,data){
    const controller=new AbortController();
    const timer=setTimeout(()=>controller.abort(),30000);
    try{
      const r=await fetch('/api/personal/'+action,{method:action==='state'?'GET':'POST',headers:{'Content-Type':'application/json','X-Niu-Token':token},...(action==='state'?{}:{body:JSON.stringify(data||{})}),signal:controller.signal});
      const result=await r.json();
      if(!r.ok)throw Error(result.error||'操作失败');
      return result;
    }catch(e){
      if(e.name==='AbortError')throw Error('请求超时：节点 30 秒没有响应。请稍后重试，或先点「刷新」确认网络状态。');
      throw e;
    }finally{clearTimeout(timer);}
  }

  // 只用 createElement 拼 DOM，不拼 HTML 字符串，避免任何注入面。
  function h(tag,props={},...kids){
    const el=document.createElement(tag);
    for(const [k,v] of Object.entries(props)){
      if(k==='class')el.className=v;
      else if(k==='text')el.textContent=v;
      else if(k.startsWith('data-')||k.startsWith('aria-'))el.setAttribute(k,v);
      else el[k]=v;
    }
    for(const kid of kids)if(kid!==null&&kid!==undefined)el.append(kid);
    return el;
  }

  const netById=id=>state.networks.find(n=>n.id===id);
  const cardKey=(nid,asset)=>nid+':'+asset;
  const cardOf=(nid,asset)=>document.querySelector('.asset-card[data-network="'+nid+'"][data-asset="'+asset+'"]');
  function addressFor(n){
    if(!state||!state.addresses)return '';
    return n.kind==='evm'?state.addresses.evm:n.kind==='doge'?state.addresses.doge:(n.test?state.addresses.btcTest:state.addresses.btc);
  }

  /* ---------------- 币标 ---------------- */
  // Built from window.NIU_COIN_ICONS (generated by tools/build-coin-icons.mjs from the
  // CC0 cryptocurrency-icons set) and rendered as inline SVG, so the wallet draws every
  // badge with no network request and no external image files.
  function coinIcon(symbol){
    const ns='http://www.w3.org/2000/svg';
    const data=(window.NIU_COIN_ICONS||{})[symbol]||{color:'#5F5E5A',paths:[]};
    const svg=document.createElementNS(ns,'svg');
    svg.setAttribute('viewBox','0 0 32 32');
    svg.setAttribute('class','coin-icon');
    svg.setAttribute('role','img');
    svg.setAttribute('aria-label',symbol+' 图标');
    const circle=document.createElementNS(ns,'circle');
    circle.setAttribute('cx','16');circle.setAttribute('cy','16');circle.setAttribute('r','16');
    circle.setAttribute('fill',data.color);
    svg.append(circle);
    for(const p of data.paths){
      const path=document.createElementNS(ns,'path');
      path.setAttribute('d',p.d);
      path.setAttribute('fill','#fff');
      if(p.opacity!==undefined)path.setAttribute('fill-opacity',String(p.opacity));
      svg.append(path);
    }
    return svg;
  }

  async function work(fn){
    if(working)return;
    working=true;
    message('正在处理…');
    try{await fn();}
    catch(e){message(e.message);}
    finally{working=false;renderVault();syncCards();if(state)history();}
  }

  /* ---------------- 卡片构建 ---------------- */

  function noteFor(n,asset){
    if(n.kind==='doge')return '真实资产。Dogecoin 无测试网可用，只花费已确认的 UTXO，首版最多 40 个输入。';
    if(n.kind==='btc')return n.test
      ?'测试网 BTC 没有实际价值，可自由试验。只花费已确认的 UTXO。'
      :'真实资产。只花费已确认的 UTXO，首版最多 40 个输入，不提供发送全部。';
    if(asset!=='ETH')return '转出需要同网络的 ETH 支付手续费，请预留少量 ETH。';
    return '转出需要预留网络手续费；ERC20 代币用 ETH 计价付费。';
  }

  function sendForm(n,asset){
    const to=h('input',{type:'text',autocomplete:'off',spellcheck:false,'data-to':''});
    const amount=h('input',{type:'text',inputmode:'decimal',autocomplete:'off','data-amount':''});
    const preview=h('pre',{class:'asset-preview','data-preview':''});
    const confirmLabel=h('span',{class:'field-k','data-confirm-label':''});
    const confirm=h('input',{type:'text',autocomplete:'off','data-confirm':''});
    const box=h('div',{'data-preview-box':'',hidden:true},
      preview,
      h('label',{class:'field'},confirmLabel,confirm),
      h('div',{class:'btn-row'},h('button',{class:'primary-btn','data-do-send':'',type:'button',text:'签名并发送'}))
    );
    return h('form',{class:'asset-send','data-send-form':'',hidden:true},
      h('p',{class:'asset-note',text:noteFor(n,asset)}),
      h('label',{class:'field'},h('span',{class:'field-k',text:'收款地址'}),to),
      h('label',{class:'field'},h('span',{class:'field-k',text:'金额（'+asset+'）'}),amount),
      h('div',{class:'btn-row'},
        h('button',{class:'primary-btn','data-prepare':'',type:'button',text:'预览金额与手续费'}),
        h('button',{class:'ghost-btn','data-cancel':'',type:'button',text:'取消'})),
      box
    );
  }

  function makeCard(n,asset){
    return h('article',{class:'asset-card '+(n.test?'is-testnet':'is-mainnet'),'data-network':n.id,'data-asset':asset},
      h('header',{class:'asset-head'},
        h('div',{class:'asset-id'},
          h('span',{class:'asset-symbol'},coinIcon(asset),document.createTextNode(asset)),
          h('span',{class:'asset-name',text:n.name})
        ),
        h('span',{class:'asset-badge '+(n.test?'is-testnet':'is-mainnet'),text:n.test?'测试网':'主网'})
      ),
      h('p',{class:'asset-balance'},h('strong',{class:'is-empty','data-balance':'',text:'未查询'}),h('span',{'data-unit':'',text:asset,hidden:true})),
      h('p',{class:'asset-pending','data-pending':'',hidden:true}),
      h('div',{class:'asset-addr'},
        h('code',{'data-addr':'',text:LOCKED}),
        h('button',{class:'mini-btn','data-copy':'',type:'button',text:'复制'})
      ),
      h('div',{class:'asset-qr','data-qr':'',hidden:true}),
      h('div',{class:'asset-actions'},
        h('button',{class:'ghost-btn','data-send-toggle':'',type:'button',text:'转出'}),
        h('button',{class:'ghost-btn','data-qr-toggle':'',type:'button',text:'二维码'}),
        h('button',{class:'ghost-btn','data-refresh':'',type:'button',text:'刷新'})
      ),
      sendForm(n,asset)
    );
  }

  function buildCards(){
    const main=$('personalAssetsMain'),test=$('personalAssetsTest');
    main.replaceChildren();test.replaceChildren();
    let mainCount=0,testCount=0;
    for(const n of state.networks)for(const asset of n.assets){
      if(n.test){test.append(makeCard(n,asset));testCount++;}
      else{main.append(makeCard(n,asset));mainCount++;}
    }
    $('countMain').textContent=String(mainCount);
    $('countTest').textContent=String(testCount);
  }

  function closeSend(card){
    const form=card.querySelector('[data-send-form]');
    if(!form)return;
    form.hidden=true;
    form.querySelector('[data-to]').value='';
    form.querySelector('[data-amount]').value='';
    form.querySelector('[data-confirm]').value='';
    form.querySelector('[data-preview-box]').hidden=true;
    draftIds.delete(cardKey(card.dataset.network,card.dataset.asset));
  }

  /* ---------------- 状态同步 ---------------- */

  function renderVault(){
    if(!state)return;
    const created=state.created,locked=state.locked;
    $('personalVaultTitle').textContent=created?'个人账户与加密备份':'创建个人账户';
    $('personalLockState').textContent=created?(locked?'已锁定':'已解锁 · 5分钟无签名操作自动锁定'):'尚未创建';
    $('personalCreate').hidden=created;
    $('personalUnlock').hidden=!created||!locked;
    $('personalLock').hidden=!created||locked;
    $('personalBackup').disabled=!created||locked;
    $('personalRestore').hidden=created;
    $('personalPasswordAgainField').hidden=created;
  }

  // Balances arrive with full 18-digit precision, which is unreadable on a card. Show at most
  // six decimals and keep the exact figure in the tooltip so nothing is lost.
  function shortAmount(text){
    if(!/^\d+(\.\d+)?$/.test(text))return text;
    const dot=text.indexOf('.');
    if(dot<0)return text;
    const whole=text.slice(0,dot),frac=text.slice(dot+1).slice(0,6).replace(/0+$/,'');
    if(frac)return whole+'.'+frac;
    return text.slice(dot+1).replace(/0/g,'')===''?whole:'<0.000001';
  }

  function syncCards(){
    if(!state)return;
    for(const n of state.networks)for(const asset of n.assets){
      const card=cardOf(n.id,asset);
      if(!card)continue;
      const addr=addressFor(n),locked=!addr;
      card.querySelector('[data-addr]').textContent=addr||LOCKED;
      card.querySelector('[data-copy]').disabled=!addr;
      card.querySelector('[data-qr-toggle]').disabled=!addr;
      card.querySelector('[data-refresh]').disabled=!addr;
      card.querySelector('[data-send-toggle]').disabled=locked||state.locked;
      card.classList.toggle('is-locked',locked||state.locked);

      const known=balances.get(n.id),balanceEl=card.querySelector('[data-balance]');
      const value=known&&known[asset]!=null?known[asset]:null;
      const perAsset=assetError.get(n.id+':'+asset),netErr=netError.get(n.id);
      if(value!=null){balanceEl.textContent=shortAmount(value);balanceEl.title=value;balanceEl.classList.remove('is-error');}
      else if(perAsset){balanceEl.textContent='查询失败';balanceEl.title=perAsset;balanceEl.classList.add('is-error');}
      else if(netErr){balanceEl.textContent='查询失败';balanceEl.title=netErr;balanceEl.classList.add('is-error');}
      else{balanceEl.textContent='未查询';balanceEl.removeAttribute('title');balanceEl.classList.remove('is-error');}
      balanceEl.classList.toggle('is-empty',value==null);
      card.querySelector('[data-unit]').hidden=value==null;
      const pend=pendingBal.get(n.id),pendEl=card.querySelector('[data-pending]');
      if(pend&&Number(pend)!==0){pendEl.hidden=false;pendEl.textContent='未确认净额 '+pend+' '+asset;}
      else pendEl.hidden=true;

      if(locked||state.locked)closeSend(card);
    }
  }

  function history(){
    const box=$('personalHistory');
    box.replaceChildren();
    const status={broadcasting:'正在广播',unknown:'广播结果未知',pending:'等待确认',confirmed:'已确认',failed:'链上执行失败'};
    for(const item of state.history){
      const row=document.createElement('div');
      row.className='personal-history-row';
      const title=document.createElement('strong');
      title.textContent=`${item.amount} ${item.asset} · ${status[item.status]||item.status}`;
      row.append(title);
      for(const text of [item.network+' · '+item.createdAt,'至 '+item.to,item.hash]){
        const p=document.createElement('p');p.textContent=text;row.append(p);
      }
      const link=document.createElement('a');
      link.textContent='在区块浏览器查看';
      link.href=item.explorer;link.target='_blank';link.rel='noopener noreferrer';
      row.append(link);
      box.append(row);
    }
    if(!state.history.length)box.textContent='尚无本机发送记录';
  }

  async function load(){
    state=await api('state');
    if(!$('personalAssetsMain').childElementCount)buildCards();
    renderVault();syncCards();history();scheduleHistoryPoll();
  }

  // Never let one unreachable endpoint stop the others: each network is queried on its own
  // and failures are reported per card instead of being swallowed.
  async function refreshNetwork(n){
    try{
      const result=await api('balance',{network:n.id});
      balances.set(n.id,result.balances||{});
      pendingBal.set(n.id,result.pending||'0');
      netError.delete(n.id);
      for(const asset of n.assets)assetError.delete(n.id+':'+asset);
      for(const [symbol,reason] of Object.entries(result.errors||{}))assetError.set(n.id+':'+symbol,reason);
      return null;
    }catch(e){
      netError.set(n.id,e.message||'查询失败');
      return e.message||'查询失败';
    }finally{syncCards();}
  }

  // The backend only learns what happened to a broadcast when it is asked, so anything still
  // in flight has to be polled — otherwise the record sits on 「等待确认」 forever.
  let historyTimer=null;
  const IN_FLIGHT=['broadcasting','pending','unknown'];
  async function syncHistory(){
    if(!state||!state.history.some(h=>IN_FLIGHT.includes(h.status)))return;
    try{state=await api('refresh');history();syncCards();}catch{/* keep the last known state */}
  }
  function scheduleHistoryPoll(){
    clearTimeout(historyTimer);
    if(!state||!state.history.some(h=>IN_FLIGHT.includes(h.status)))return;
    historyTimer=setTimeout(async()=>{await syncHistory();scheduleHistoryPoll();},15000);
  }

  /* ---------------- 交互 ---------------- */

  $('page-personal').addEventListener('submit',e=>e.preventDefault());

  $('page-personal').addEventListener('click',async e=>{
    const btn=e.target.closest('button');
    const card=e.target.closest('.asset-card');
    if(!btn||!card)return;
    const n=netById(card.dataset.network),asset=card.dataset.asset;
    if(!n)return;

    if(btn.hasAttribute('data-copy')){
      const addr=addressFor(n);
      if(!addr){message('请先解锁个人钱包，再复制收款地址。');return;}
      try{await navigator.clipboard.writeText(addr);message('已复制 '+n.name+' 的 '+asset+' 收款地址。');}
      catch{message('复制失败，请手动选中地址复制。');}
      return;
    }

    if(btn.hasAttribute('data-qr-toggle')){
      const qrBox=card.querySelector('[data-qr]');
      if(!qrBox.hidden){qrBox.hidden=true;btn.textContent='二维码';return;}
      const addr=addressFor(n);
      if(!addr){message('请先解锁个人钱包，再显示二维码。');return;}
      try{
        if(!qrBox.childElementCount){
          const q=await api('qr',{address:addr});
          const doc=new DOMParser().parseFromString(q.svg,'image/svg+xml');
          qrBox.append(document.importNode(doc.documentElement,true));
        }
        qrBox.hidden=false;btn.textContent='收起二维码';
      }catch(err){message(err.message);}
      return;
    }

    if(btn.hasAttribute('data-refresh')){
      work(async()=>{
        const reason=await refreshNetwork(n);
        await syncHistory();
        message(reason?'查询失败：'+reason:'已更新 '+n.name+' 的 '+asset+' 余额。');
      });
      return;
    }

    if(btn.hasAttribute('data-send-toggle')){
      const form=card.querySelector('[data-send-form]');
      if(form.hidden){form.hidden=false;btn.textContent='收起';}
      else{closeSend(card);btn.textContent='转出';}
      return;
    }

    if(btn.hasAttribute('data-cancel')){
      closeSend(card);
      card.querySelector('[data-send-toggle]').textContent='转出';
      message('已取消此次预览。');
      return;
    }

    const form=card.querySelector('[data-send-form]');

    if(btn.hasAttribute('data-prepare')){
      work(async()=>{
        const draft=await api('prepare',{
          network:n.id,asset,
          to:form.querySelector('[data-to]').value.trim(),
          amount:form.querySelector('[data-amount]').value.trim()
        });
        draftIds.set(cardKey(n.id,asset),draft.draftId);
        form.querySelector('[data-preview]').textContent=
          '网络：'+draft.network+'\n付款：'+draft.from+'\n收款：'+draft.to+'\n金额：'+draft.amount+' '+draft.asset+'\n手续费：'+draft.fee+'\n预览90秒后过期。';
        form.querySelector('[data-confirm-label]').textContent='核对后输入：'+(draft.test?'确认测试网发送':'确认主网发送');
        form.querySelector('[data-confirm]').value='';
        form.querySelector('[data-preview-box]').hidden=false;
        message('请核对完整收款地址、网络、金额和手续费。');
      });
      return;
    }

    if(btn.hasAttribute('data-do-send')){
      work(async()=>{
        const id=draftIds.get(cardKey(n.id,asset));
        if(!id)throw Error('请先预览交易');
        const confirmation=form.querySelector('[data-confirm]').value;
        closeSend(card);
        card.querySelector('[data-send-toggle]').textContent='转出';
        const r=await api('send',{draftId:id,confirmation});
        message('已提交广播，等待链上确认：'+r.hash);
        state=await api('state');
        scheduleHistoryPoll();
      });
    }
  });

  function selectChain(chain){
    for(const tab of document.querySelectorAll('.chain-tab')){
      const active=tab.dataset.chain===chain;
      tab.classList.toggle('is-active',active);
      tab.setAttribute('aria-selected',String(active));
    }
    $('personalAssetsMain').hidden=chain!=='main';
    $('personalAssetsTest').hidden=chain!=='test';
  }
  for(const tab of document.querySelectorAll('.chain-tab'))tab.addEventListener('click',()=>selectChain(tab.dataset.chain));

  $('personalRefreshAll').onclick=()=>work(async()=>{
    if(!state.addresses)throw Error('请先解锁个人钱包，再查询余额。');
    const failed=[];
    for(const n of state.networks){
      const reason=await refreshNetwork(n);
      if(reason)failed.push(n.name+'：'+reason);
    }
    await syncHistory();
    scheduleHistoryPoll();
    message(failed.length
      ?'有 '+failed.length+' 个网络查询失败（其余已更新）：'+failed.join('；')
      :'已刷新全部网络余额。');
  });

  /* ---------------- 账户操作（与原版一致） ---------------- */

  function password(){
    const p=$('personalPassword').value;
    if(p.length<12)throw Error('请输入至少12个字符的个人钱包口令');
    return p;
  }
  function erase(){$('personalPassword').value='';$('personalPasswordAgain').value='';}

  $('personalCreate').onclick=()=>work(async()=>{
    const p=password();
    if(p!==$('personalPasswordAgain').value)throw Error('两次口令不一致');
    await api('create',{password:p});
    erase();await load();
    message('独立账户已创建。请重新输入口令并导出加密备份，再开始收款。');
  });
  $('personalUnlock').onclick=()=>work(async()=>{
    try{await api('unlock',{password:password()});}finally{erase();}
    await load();message('已解锁。');
  });
  $('personalLock').onclick=()=>work(async()=>{
    await api('lock');erase();await load();message('已锁定。');
  });
  $('personalBackup').onclick=()=>work(async()=>{
    let b;
    try{b=await api('backup',{password:password()});}finally{erase();}
    const blob=new Blob([JSON.stringify(b,null,2)],{type:'application/json'}),url=URL.createObjectURL(blob),a=document.createElement('a');
    a.href=url;a.download='NIU-Personal-Encrypted-Backup-'+new Date().toISOString().slice(0,10)+'.json';
    a.click();setTimeout(()=>URL.revokeObjectURL(url),10000);
    message('已发起下载加密备份。请确认文件已保存，口令另外保管。原有NIU账户需要单独备份。');
  });
  $('personalRestore').onclick=()=>{
    try{password();$('personalRestoreFile').click();}catch(e){message(e.message);}
  };
  $('personalRestoreFile').onchange=()=>work(async()=>{
    const f=$('personalRestoreFile').files[0];
    if(!f)return;
    if(f.size>16384)throw Error('备份文件过大');
    try{await api('restore',{content:await f.text(),password:password()});}
    finally{erase();$('personalRestoreFile').value='';}
    await load();message('个人钱包已恢复，请核对卡片上的收款地址。');
  });

  document.querySelector('[data-page="personal"]').addEventListener('click',()=>work(load));
  window.addEventListener('pagehide',erase);
  setInterval(async()=>{
    if(!state||working||!document.querySelector('#page-personal.is-active'))return;
    try{
      const next=await api('state');
      if(next.locked&&!state.locked){message('个人钱包已自动锁定。');}
      state=next;renderVault();syncCards();
    }catch{}
  },5000);

  load().catch(e=>message(e.message));
})();
