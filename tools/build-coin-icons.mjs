// Generates public/coin-icons.js from the official cryptocurrency-icons artwork.
// Run: node tools/build-coin-icons.mjs   (downloads once into .tmp-icons/ and caches)
//
// Source: https://github.com/spothq/cryptocurrency-icons (CC0-1.0, public domain).
// The icons are inlined into the page so the wallet still renders with no network.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {join} from 'node:path';

const SOURCE='https://cdn.jsdelivr.net/npm/cryptocurrency-icons@0.18.1/svg/color';
const cache='.tmp-icons';
const MAP=[['BTC','btc'],['ETH','eth'],['USDT','usdt'],['USDC','usdc'],['DOGE','doge']];

mkdirSync(cache,{recursive:true});
const svgs={};
for(const [symbol,slug] of MAP){
  const file=join(cache,slug+'.svg');
  if(!existsSync(file)){
    const res=await fetch(`${SOURCE}/${slug}.svg`);
    if(!res.ok)throw Error(`download failed ${slug}: ${res.status}`);
    writeFileSync(file,await res.text());
  }
  svgs[symbol]=readFileSync(file,'utf8');
}

const attr=(tag,name)=>{
  const m=tag.match(new RegExp(name+'="([^"]*)"'));
  return m?m[1]:null;
};

const icons={};
for(const [symbol,slug] of MAP){
  const svg=svgs[symbol];
  const viewBox=attr(svg,'viewBox');
  if(viewBox!=='0 0 32 32')throw Error(`${slug}: unexpected viewBox ${viewBox}`);
  const circle=svg.match(/<circle[^>]*>/);
  if(!circle)throw Error(`${slug}: no background circle`);
  const color=attr(circle[0],'fill');
  if(!color||!color.startsWith('#'))throw Error(`${slug}: no circle colour`);
  const paths=[...svg.matchAll(/<path[^>]*>/g)].map(([tag])=>{
    const d=attr(tag,'d');
    if(!d)throw Error(`${slug}: path without d`);
    const fill=attr(tag,'fill');
    if(fill&&fill.toLowerCase()!=='#fff')throw Error(`${slug}: unexpected path fill ${fill}`);
    const opacity=attr(tag,'fill-opacity');
    return opacity?{d,opacity:Number(opacity)}:{d};
  });
  if(!paths.length)throw Error(`${slug}: no glyph paths`);
  icons[symbol]={color,paths};
}

const body=Object.entries(icons).map(([symbol,{color,paths}])=>{
  const list=paths.map(p=>p.opacity===undefined
    ?`      {d:'${p.d}'}`
    :`      {d:'${p.d}',opacity:${p.opacity}}`).join(',\n');
  return `  ${symbol}:{\n    color:'${color}',\n    paths:[\n${list}\n    ]\n  }`;
}).join(',\n');

const out=`// Generated by tools/build-coin-icons.mjs - do not edit by hand.
// Artwork: cryptocurrency-icons by spothq, CC0-1.0 (public domain).
// Inlined so the page renders correctly with no network access.
(function(){
  'use strict';
  window.NIU_COIN_ICONS=Object.freeze({
${body}
  });
})();
`;

writeFileSync('public/coin-icons.js',out);
console.log('wrote public/coin-icons.js');
for(const [symbol,{color,paths}] of Object.entries(icons)){
  console.log(` ${symbol.padEnd(5)} ${color}  ${paths.length} path(s)  ${out.length} bytes total`);
}
